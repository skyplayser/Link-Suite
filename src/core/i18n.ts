export type Lang = "de" | "en";

/** Systemsprache → Oberflächensprache: Deutsch für de-*, sonst Englisch (wie VJ-Link detectLang). */
export function detectLang(langs: readonly string[]): Lang {
  for (const l of langs) {
    const k = l.toLowerCase().slice(0, 2);
    if (k === "de") return "de";
    if (k === "en") return "en";
  }
  return "en";
}

