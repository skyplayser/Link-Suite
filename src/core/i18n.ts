/** Text zum Schlüssel in der Sprache, Platzhalter ersetzt. Unbekannter Schlüssel → der Schlüssel selbst. */
export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const e = TEXTS[key];
  let s = e ? (lang === "en" && e.en ? e.en : e.de) : key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
  return s;
}
